// Rebuild the playable visual asset and collision hulls from the saved approved concept.
import {writeFile} from 'node:fs/promises';
import {Box3} from 'three';
import {GLTFExporter} from 'three/addons/exporters/GLTFExporter.js';
import {createRooftop} from '../art/prototypes/rooftop/approved-v1/scene.mjs';
import {ROOFTOP_SCALE} from '../shared/rooftop-config.js';

globalThis.FileReader=class {
  readAsArrayBuffer(blob){blob.arrayBuffer().then(value=>{this.result=value;this.onloadend?.();});}
  readAsDataURL(blob){blob.arrayBuffer().then(value=>{this.result=`data:${blob.type};base64,${Buffer.from(value).toString('base64')}`;this.onloadend?.();});}
};
const root=createRooftop();
for(const child of [...root.children]) {
  if(/mannequin/i.test(child.name)||['Low pipe crossing','Pipe support'].includes(child.name))root.remove(child);
  // The original left skylight pinched the terrace into a sub-body-width gap.
  // Move its entire assembly into the wider lane; keep approved-v1 untouched.
  if(/skylight/i.test(child.name)&&child.position.x<2)child.position.x+=1;
}
root.scale.set(ROOFTOP_SCALE,1,ROOFTOP_SCALE);
root.position.y=-.145;root.name='Skyline rooftop';root.userData={map:'skyline',approvedConcept:'approved-v1'};
root.updateMatrixWorld(true);
const names=new Set(['West roof terrace','West roof terrace coping','East mechanical terrace','East mechanical terrace coping',
  'West access incline','East terrace stair','Connecting maintenance bridge','Bridge grating','Bridge step-up',
  'West rooftop air handler','Air handler top fan','East raised duct obstacle','Duct return elbow',
  'Skylight curb','Sloped skylight glazing','Low pipe crossing','Pipe support','Exhaust plinth','Exhaust obstacle','Mushroom vent cap',
  'Service penthouse','Penthouse roof coping','Access stair','Raised service deck','Connecting rear service plinth',
  'Rear plinth top','West rear roof shoulder','East rear roof shoulder','HVAC housing','Fan rim','Vent duct','Vent elbow',
  'Wood water tank','Tank conical roof']);
const round=n=>Math.round(n*1e6)/1e6;
const hulls=[];
for(const mesh of root.children) {
  if(!names.has(mesh.name))continue;
  const bounds=new Box3().setFromObject(mesh),min=bounds.min,max=bounds.max;
  const h={name:mesh.name,x:round((min.x+max.x)/2),z:round((min.z+max.z)/2),hw:round((max.x-min.x)/2),hd:round((max.z-min.z)/2),bottom:round(min.y),y:round(max.y)};
  if(mesh.name==='West access incline') {h.slopeZ=round(-1.5/(3.5*.72*ROOFTOP_SCALE));h.y=round((.15+1.65)/2-.145);}
  if(mesh.name==='Sloped skylight glazing') {h.slopeZ=round(-Math.tan(.23)/(.72*ROOFTOP_SCALE));h.y=round(1.03-.145+.06/Math.cos(.23));}
  hulls.push(h);
}
const roof=new Box3().setFromObject(root.getObjectByName('Oversailing roof slab'));
const floor={x:round((roof.min.x+roof.max.x)/2),z:round((roof.min.z+roof.max.z)/2),hw:round((roof.max.x-roof.min.x)/2),hd:round((roof.max.z-roof.min.z)/2)};
const data=await new GLTFExporter().parseAsync(root,{binary:true});
await writeFile(new URL('../host/assets/maps/skyline.glb',import.meta.url),Buffer.from(data));
await writeFile(new URL('../host/src/rooftop-hulls.js',import.meta.url),`// Generated by scripts/build-rooftop.mjs from approved-v1. Do not edit by hand.\nexport const ROOFTOP_BOUNDS = ${JSON.stringify(floor)};\nexport const ROOFTOP_HULLS = ${JSON.stringify(hulls,null,2)};\n`);
console.log(`Skyline: ${hulls.length} collision hulls, ${data.byteLength} GLB bytes`);
