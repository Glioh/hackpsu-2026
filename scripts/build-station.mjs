// Build playable geometry and collision from the enlarged station concept.
import {writeFile} from 'node:fs/promises';
import {Box3} from 'three';
import {GLTFExporter} from 'three/addons/exporters/GLTFExporter.js';
import {createStation} from '../art/prototypes/station/scene.mjs';
globalThis.FileReader=class {
  readAsArrayBuffer(blob){blob.arrayBuffer().then(value=>{this.result=value;this.onloadend?.();});}
  readAsDataURL(blob){blob.arrayBuffer().then(value=>{this.result=`data:${blob.type};base64,${Buffer.from(value).toString('base64')}`;this.onloadend?.();});}
};
const {root,trains}=createStation({random:()=>.5});
for(const child of [...root.children])if(/Fighter/.test(child.name))root.remove(child);
trains.forEach(train=>{train.visible=true;train.position.x=0;});
root.updateMatrixWorld(true);
const physical=/^(Island fighting platform|Platform stone surface|West raised waiting terrace|West terrace coping|West broad stair|East luggage podium|Podium stair|Overhead transfer footbridge|Footbridge walkway|Bridge guard post|Bridge handrail|Bridge pier|Transfer staircase|Upper stair landing|Bench seat|Bench back|Bench leg|Ticket machine|Luggage stack|Hall column|Outer station platform)$/;
const round=n=>Math.round(n*1e6)/1e6;
const hulls=root.children.filter(mesh=>mesh.isMesh&&physical.test(mesh.name)).map(mesh=>{
  const {min,max}=new Box3().setFromObject(mesh);
  return {name:mesh.name,x:round((min.x+max.x)/2),z:round((min.z+max.z)/2),hw:round((max.x-min.x)/2),hd:round((max.z-min.z)/2),bottom:round(min.y),y:round(max.y)};
});
// Tracks beyond the station and the foundation are scenery. Bed ends are open drops.
for(const z of [-11.2,11.2])hulls.push({name:'Track bed',x:0,z,hw:27,hd:3.01,bottom:-.7,y:-.37});
const data=await new GLTFExporter().parseAsync(root,{binary:true});
await writeFile(new URL('../host/assets/maps/station.glb',import.meta.url),Buffer.from(data));
await writeFile(new URL('../host/src/station-hulls.js',import.meta.url),`// Generated by scripts/build-station.mjs.\nexport const STATION_HULLS = ${JSON.stringify(hulls,null,2)};\n`);
console.log(`Station: ${hulls.length} collision hulls, ${data.byteLength} GLB bytes`);
